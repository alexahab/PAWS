-- PostgreSQL 14+; create database and role separately (see README)
CREATE TABLE IF NOT EXISTS users (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(50) NOT NULL,
 email VARCHAR(254) NOT NULL UNIQUE,
 password_hash TEXT NOT NULL,
 role VARCHAR(16) NOT NULL DEFAULT 'user' CHECK (role IN ('user','shelter','moderator','admin')),
 is_blocked BOOLEAN NOT NULL DEFAULT FALSE,
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS ads (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 kind VARCHAR(8) NOT NULL CHECK (kind IN ('lost','found')),
 animal_name VARCHAR(80) NOT NULL DEFAULT '',
 species VARCHAR(60) NOT NULL,
 city VARCHAR(100) NOT NULL,
 district VARCHAR(100) NOT NULL,
 description TEXT NOT NULL CHECK (char_length(description) BETWEEN 20 AND 300),
 contact VARCHAR(150) NOT NULL,
 image_filename TEXT NOT NULL,
 status VARCHAR(16) NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','published','rejected','closed')),
 rejection_reason TEXT,
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
 updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_ads_status_date ON ads(status, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_ads_user ON ads(user_id);
CREATE INDEX IF NOT EXISTS idx_ads_city ON ads(city);
CREATE TABLE IF NOT EXISTS likes (
 user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 ad_id BIGINT NOT NULL REFERENCES ads(id) ON DELETE CASCADE,
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
 PRIMARY KEY (user_id, ad_id)
);
CREATE TABLE IF NOT EXISTS reports (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 ad_id BIGINT NOT NULL REFERENCES ads(id) ON DELETE CASCADE,
 reason TEXT NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE INDEX IF NOT EXISTS idx_reports_ad ON reports(ad_id);
